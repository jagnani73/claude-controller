import { randomUUID } from "node:crypto";
import { realpathSync, statSync } from "node:fs";
import { isAbsolute, relative, sep } from "node:path";
import {
  TERMINAL_LIMITS as LIMIT,
  type TerminalClientMessage,
  type TerminalInfo,
  type TerminalServerMessage,
} from "common/terminal-types";
import type { WebSocket } from "ws";
import type { SessionManager } from "./session-manager.service.js";
import { TerminalProcess, terminalShell } from "./terminal-process.js";

type Chunk = { start: number; end: number; data: string };
type Terminal = {
  info: TerminalInfo;
  process: TerminalProcess | null;
  history: Chunk[];
  subscribers: Map<WebSocket, { cursor: number; ack: number }>;
  dirtyState: Set<WebSocket>;
  controller: WebSocket | null;
  lastActivity: number;
  inputWindow: number;
  inputBytes: number;
};
const UUID = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i;

/** Independent of SessionBus, hooks, and the Claude PTY. One per HTTP server. */
export class TerminalManager {
  private terminals = new Map<string, Terminal>();
  // Creation IDs are UUIDs generated by the explicit New action, never by
  // reconnect. Bounded receipts survive close; old retries fail, not respawn.
  private creations = new Map<string, { sessionId: string; id: string; at: number }>();
  private timer: ReturnType<typeof setInterval>;
  private disposed = false;
  private idleMs: number;
  private rates = new WeakMap<WebSocket, { at: number; count: number }>();

  constructor(
    private workDir: string,
    private sessions: Pick<SessionManager, "get">,
    idleMinutes = Number(process.env.TERMINAL_IDLE_MINUTES ?? 30),
  ) {
    this.idleMs =
      Number.isFinite(idleMinutes) && idleMinutes >= 0 ? idleMinutes * 60_000 : 30 * 60_000;
    this.timer = setInterval(() => this.tick(), 50);
    this.timer.unref();
  }

  /** Narrow AND runtime-validate at this boundary, rather than trusting WS JSON. */
  handle(ws: WebSocket, value: unknown): boolean {
    if (
      !value ||
      typeof value !== "object" ||
      !("type" in value) ||
      typeof value.type !== "string" ||
      !value.type.startsWith("terminal_")
    )
      return false;
    const msg = value as TerminalClientMessage;
    try {
      if (this.disposed) throw new Error("Terminal service is stopping");
      if (Buffer.byteLength(JSON.stringify(value)) > LIMIT.queueBytes)
        throw new Error("Terminal request exceeds 64 KiB");
      let rate = this.rates.get(ws);
      if (!rate || Date.now() - rate.at >= 1000) {
        rate = { at: Date.now(), count: 0 };
        this.rates.set(ws, rate);
      }
      // Cleanup must remain available after a burst: otherwise an unmounted
      // viewer can keep control forever despite successfully sending release.
      if (
        msg.type !== "terminal_output_ack" &&
        msg.type !== "terminal_unsubscribe" &&
        ++rate.count > 120
      )
        throw new Error("Terminal request rate exceeded");
      if (
        typeof msg.requestId !== "string" ||
        !UUID.test(msg.requestId) ||
        typeof msg.sessionId !== "string" ||
        msg.sessionId.length > 128
      )
        throw new Error("Invalid terminal request");
      if (msg.type === "terminal_list") {
        this.send(ws, {
          type: "terminal_list",
          sessionId: msg.sessionId,
          requestId: msg.requestId,
          terminals: [...this.terminals.values()]
            .filter((t) => t.info.sessionId === msg.sessionId)
            .map((t) => t.info),
        });
        return true;
      }
      if (msg.type === "terminal_create") {
        this.create(ws, msg);
        return true;
      }
      if (!("terminalId" in msg) || typeof msg.terminalId !== "string")
        throw new Error("Invalid terminal target");
      const terminal = this.terminals.get(msg.terminalId);
      // A removal notification triggers view cleanup after the registry entry
      // is gone. Releasing an absent subscription is a successful no-op.
      if (!terminal && msg.type === "terminal_unsubscribe") {
        this.send(ws, {
          type: "terminal_ack",
          sessionId: msg.sessionId,
          terminalId: msg.terminalId,
          requestId: msg.requestId,
        });
        return true;
      }
      if (!terminal || terminal.info.sessionId !== msg.sessionId)
        throw new Error("Terminal not found in this session");
      const target = { sessionId: msg.sessionId, terminalId: msg.terminalId };
      switch (msg.type) {
        case "terminal_subscribe": {
          if (!Number.isSafeInteger(msg.after) || msg.after < 0)
            throw new Error("Invalid output cursor");
          if (!terminal.subscribers.has(ws) && terminal.subscribers.size >= 16)
            throw new Error("Too many terminal viewers");
          terminal.subscribers.set(ws, { cursor: msg.after, ack: msg.after });
          this.state(ws, terminal, msg.requestId);
          this.flush(ws, terminal);
          break;
        }
        case "terminal_output_ack": {
          const subscription = terminal.subscribers.get(ws);
          if (
            !subscription ||
            !Number.isSafeInteger(msg.after) ||
            msg.after < subscription.ack ||
            msg.after > subscription.cursor
          )
            throw new Error("Invalid terminal acknowledgement");
          subscription.ack = msg.after;
          break;
        }
        case "terminal_unsubscribe":
          terminal.subscribers.delete(ws);
          terminal.dirtyState.delete(ws);
          if (terminal.controller === ws) {
            terminal.controller = null;
            this.broadcastState(terminal);
          }
          this.send(ws, { type: "terminal_ack", ...target, requestId: msg.requestId });
          break;
        case "terminal_claim":
          if (!terminal.subscribers.has(ws)) throw new Error("Subscribe before taking control");
          if (terminal.controller && terminal.controller !== ws)
            throw new Error("Another viewer controls this terminal. Ask them to release control.");
          if (terminal.info.state !== "running") throw new Error("Terminal is not running");
          terminal.controller = ws;
          terminal.lastActivity = Date.now();
          this.broadcastState(terminal);
          this.state(ws, terminal, msg.requestId);
          break;
        case "terminal_release":
          this.requireController(ws, terminal);
          terminal.controller = null;
          this.broadcastState(terminal);
          this.state(ws, terminal, msg.requestId);
          break;
        case "terminal_input": {
          this.requireController(ws, terminal);
          if (typeof msg.data !== "string" || Buffer.byteLength(msg.data) > LIMIT.inputBytes)
            throw new Error("Input exceeds 8 KiB; paste smaller chunks");
          const now = Date.now();
          if (now - terminal.inputWindow >= 1000) {
            terminal.inputWindow = now;
            terminal.inputBytes = 0;
          }
          terminal.inputBytes += Buffer.byteLength(msg.data);
          if (terminal.inputBytes > LIMIT.queueBytes)
            throw new Error("Input rate exceeded; input was not sent");
          if (
            terminal.info.state !== "running" ||
            !terminal.process?.send({ type: "input", data: msg.data })
          )
            throw new Error(
              "Terminal input could not be delivered; it will not be retried automatically",
            );
          terminal.lastActivity = now;
          this.send(ws, { type: "terminal_ack", ...target, requestId: msg.requestId });
          break;
        }
        case "terminal_resize":
          this.requireController(ws, terminal);
          this.dimensions(msg.cols, msg.rows);
          if (!terminal.process?.send({ type: "resize", cols: msg.cols, rows: msg.rows }))
            throw new Error("Resize could not be delivered");
          terminal.info.cols = msg.cols;
          terminal.info.rows = msg.rows;
          this.broadcastState(terminal);
          this.state(ws, terminal, msg.requestId);
          break;
        case "terminal_close":
          if (terminal.controller && terminal.controller !== ws)
            throw new Error("Only the controlling viewer can close this terminal");
          if (terminal.info.state === "exited" || terminal.info.state === "error") {
            this.terminals.delete(terminal.info.id);
            // Tell every attached viewer, not just the remover. A generic ACK
            // cannot distinguish deletion from a closing-state race in the UI.
            for (const viewer of new Set([ws, ...terminal.subscribers.keys()])) {
              if (
                !this.send(viewer, {
                  type: "terminal_removed",
                  ...target,
                  ...(viewer === ws ? { requestId: msg.requestId } : {}),
                })
              ) {
                // A connected viewer that missed removal must refresh its list
                // on reconnect rather than retain a terminal that no longer exists.
                viewer.close(1013, "Terminal list changed; reconnect");
              }
            }
            terminal.subscribers.clear();
            terminal.dirtyState.clear();
            terminal.controller = null;
            terminal.history = [];
          } else {
            this.stop(terminal);
            this.state(ws, terminal, msg.requestId);
          }
          break;
        default:
          throw new Error("Unknown terminal request");
      }
    } catch (error) {
      this.send(ws, {
        type: "terminal_error",
        sessionId: typeof msg.sessionId === "string" ? msg.sessionId.slice(0, 128) : "",
        requestId: typeof msg.requestId === "string" ? msg.requestId.slice(0, 128) : "",
        message: error instanceof Error ? error.message : "Terminal request failed",
      });
    }
    return true;
  }

  private dimensions(cols: number, rows: number): void {
    if (
      !Number.isInteger(cols) ||
      cols < LIMIT.minCols ||
      cols > LIMIT.maxCols ||
      !Number.isInteger(rows) ||
      rows < LIMIT.minRows ||
      rows > LIMIT.maxRows
    )
      throw new Error("Invalid terminal dimensions");
  }

  private create(
    ws: WebSocket,
    msg: Extract<TerminalClientMessage, { type: "terminal_create" }>,
  ): void {
    const prior = this.creations.get(msg.requestId);
    if (prior) {
      if (prior.sessionId !== msg.sessionId)
        throw new Error("Creation request belongs to a different session");
      const terminal = this.terminals.get(prior.id);
      if (!terminal)
        throw new Error(
          "That creation request has already finished; use New terminal for a new shell",
        );
      this.state(ws, terminal, msg.requestId);
      return;
    }
    this.dimensions(msg.cols, msg.rows);
    const session = this.sessions.get(msg.sessionId);
    if (!session) throw new Error("Open a known Claude session before creating a terminal");
    const root = realpathSync(this.workDir);
    const cwd = realpathSync(session.config.cwd);
    const rel = relative(root, cwd);
    if (
      isAbsolute(rel) ||
      rel === ".." ||
      rel.startsWith(`..${sep}`) ||
      !statSync(cwd).isDirectory()
    )
      throw new Error("Session directory is outside the configured workspace");
    if (
      this.terminals.size >= LIMIT.total ||
      [...this.terminals.values()].filter((t) => t.info.sessionId === msg.sessionId).length >=
        LIMIT.perSession
    )
      throw new Error("Terminal limit reached; close/remove an existing terminal first");
    // Do not evict idempotency keys on pressure: an ancient delayed create must
    // never become a new shell. Bounded for this server lifetime; restart clears.
    if (this.creations.size >= 4096)
      throw new Error(
        "Terminal creation receipt limit reached; restart the server before creating more",
      );
    const shell = terminalShell();
    const terminal: Terminal = {
      info: {
        id: randomUUID(),
        sessionId: msg.sessionId,
        cwd,
        shell: shell.shell,
        state: "starting",
        exitCode: null,
        cols: msg.cols,
        rows: msg.rows,
        firstSeq: 0,
        nextSeq: 0,
        controlled: false,
      },
      process: null,
      history: [],
      subscribers: new Map(),
      dirtyState: new Set(),
      controller: null,
      lastActivity: Date.now(),
      inputWindow: 0,
      inputBytes: 0,
    };
    this.terminals.set(terminal.info.id, terminal);
    this.creations.set(msg.requestId, {
      sessionId: msg.sessionId,
      id: terminal.info.id,
      at: Date.now(),
    });
    try {
      terminal.process = new TerminalProcess(
        { cwd, cols: msg.cols, rows: msg.rows, shell },
        (event) => {
          if (event.type === "data") this.output(terminal, event.data);
          else if (event.type === "ready") {
            if (terminal.info.state === "starting") terminal.info.state = "running";
            this.broadcastState(terminal);
          } else {
            terminal.info.state = event.type === "error" ? "error" : "exited";
            if (event.type === "error") terminal.info.error = event.message;
            else terminal.info.exitCode = event.exitCode;
            terminal.controller = null;
            terminal.process = null;
            this.broadcastState(terminal);
          }
        },
      );
    } catch (error) {
      terminal.info.state = "error";
      terminal.info.error = String(error);
    }
    this.state(ws, terminal, msg.requestId);
  }

  private requireController(ws: WebSocket, terminal: Terminal): void {
    if (terminal.controller !== ws)
      throw new Error("Read-only terminal. Take control before typing or resizing.");
  }

  private output(terminal: Terminal, data: string): void {
    const start = terminal.info.nextSeq;
    const end = start + Buffer.byteLength(data);
    terminal.info.nextSeq = end;
    terminal.history.push({ start, end, data });
    while (
      terminal.history.length &&
      (end - (terminal.history[0]?.start ?? end) > LIMIT.scrollbackBytes ||
        terminal.history.length > 8192)
    )
      terminal.history.shift();
    terminal.info.firstSeq = terminal.history[0]?.start ?? end;
    // Output isn't user activity: an unattended `yes` must still expire.
  }

  private flush(ws: WebSocket, terminal: Terminal): void {
    if (ws.readyState !== ws.OPEN) {
      this.disconnect(ws);
      return;
    }
    const subscription = terminal.subscribers.get(ws);
    if (!subscription || ws.bufferedAmount > LIMIT.socketBytes) return;
    let { cursor } = subscription;
    if (cursor - subscription.ack >= LIMIT.queueBytes) return;
    if (
      cursor < terminal.info.firstSeq ||
      cursor > terminal.info.nextSeq ||
      (cursor !== terminal.info.nextSeq && !terminal.history.some((c) => c.start === cursor))
    ) {
      // Never reset the byte window while old writes are still unacknowledged.
      // Otherwise repeated truncation could bypass renderer backpressure.
      if (subscription.ack !== cursor) return;
      if (
        !this.send(ws, {
          type: "terminal_gap",
          sessionId: terminal.info.sessionId,
          terminalId: terminal.info.id,
          requested: cursor,
          available: terminal.info.firstSeq,
        })
      )
        return;
      cursor = terminal.info.firstSeq;
      subscription.cursor = cursor;
      subscription.ack = cursor;
    }
    let bytes = 0;
    for (const chunk of terminal.history) {
      if (chunk.start < cursor) continue;
      if (bytes >= LIMIT.queueBytes || chunk.end - subscription.ack > LIMIT.queueBytes) break;
      if (
        !this.send(ws, {
          type: "terminal_output",
          sessionId: terminal.info.sessionId,
          terminalId: terminal.info.id,
          ...chunk,
        })
      )
        break;
      bytes += chunk.end - chunk.start;
      subscription.cursor = chunk.end;
    }
  }

  private send(ws: WebSocket, msg: TerminalServerMessage): boolean {
    if (ws.readyState !== ws.OPEN) return false;
    const data = JSON.stringify(msg);
    if (ws.bufferedAmount + Buffer.byteLength(data) > LIMIT.socketBytes) return false;
    ws.send(data);
    return true;
  }

  private state(ws: WebSocket, terminal: Terminal, requestId?: string): void {
    terminal.info.controlled = terminal.controller !== null;
    const delivered = this.send(ws, {
      type: "terminal_state",
      sessionId: terminal.info.sessionId,
      requestId,
      terminal: { ...terminal.info },
      controller: terminal.controller === ws,
    });
    if (delivered) terminal.dirtyState.delete(ws);
    else if (terminal.subscribers.has(ws)) terminal.dirtyState.add(ws);
  }

  private broadcastState(terminal: Terminal): void {
    terminal.info.controlled = terminal.controller !== null;
    for (const ws of terminal.subscribers.keys()) this.state(ws, terminal);
  }

  private stop(terminal: Terminal): void {
    if (!terminal.process) return;
    terminal.info.state = "closing";
    terminal.process.close();
    this.broadcastState(terminal);
  }

  private tick(): void {
    for (const terminal of this.terminals.values()) {
      for (const ws of terminal.subscribers.keys()) {
        if (terminal.dirtyState.has(ws)) this.state(ws, terminal);
        this.flush(ws, terminal);
      }
      if (
        this.idleMs &&
        Date.now() - terminal.lastActivity > this.idleMs &&
        terminal.info.state === "running"
      )
        this.stop(terminal);
    }
  }

  disconnect(ws: WebSocket): void {
    for (const terminal of this.terminals.values()) {
      terminal.subscribers.delete(ws);
      terminal.dirtyState.delete(ws);
      if (terminal.controller === ws) {
        terminal.controller = null;
        this.broadcastState(terminal);
      }
    }
  }

  dispose(): void {
    if (this.disposed) return;
    this.disposed = true;
    clearInterval(this.timer);
    for (const terminal of this.terminals.values()) {
      terminal.process?.close();
      terminal.subscribers.clear();
      terminal.dirtyState.clear();
      terminal.controller = null;
      terminal.history = [];
    }
    this.terminals.clear();
    this.creations.clear();
  }
}
